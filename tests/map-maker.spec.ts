import { test, expect } from '@playwright/test';
test('creates a styled boundary map, imports CSV and prepares a printable image', async ({page}) => {
  test.setTimeout(120000);
  // Forward the approved public topographic service through Node's verified proxy/CA.
  await page.route(/https:\/\/(server|services)\.arcgisonline\.com\/ArcGIS\/rest\/services\/World_Topo_Map\//, async route => {
    const response = await fetch(route.request().url());
    const body=Buffer.from(await response.arrayBuffer());
    await route.fulfill({ status: response.status, contentType: response.headers.get('content-type') || 'application/octet-stream', body });
  });
  await page.route('https://landsat2.arcgis.com/**', route => route.fulfill({json:{error:{code:500,message:'Test service unavailable'}}}));
  await page.goto('/map?view=2d');
  await expect(page.getByText('EXPLORER READY')).toBeVisible({timeout:45000});
  await page.getByRole('button',{name:'Map maker',exact:true}).click();
  await page.getByLabel('Bounding coordinates').fill('-119.62, 37.65, -119.48, 37.76');
  await page.getByRole('button',{name:'Apply coordinates'}).click();
  await expect(page.getByText('Boundary ready.',{exact:false})).toBeVisible({timeout:30000});
  await page.getByLabel('Topographic style').selectOption('parchment');
  await expect(page.getByRole('button',{name:'Create print preview'})).toBeEnabled();
  await page.getByRole('button',{name:'Add my data',exact:false}).click();
  await page.getByRole('dialog').locator('input[type=file]').setInputFiles({name:'places.csv',mimeType:'text/csv',buffer:Buffer.from('name,latitude,longitude\nMy trailhead,37.70,-119.55')});
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'Create print preview'}).click();
  const preview=page.getByRole('dialog',{name:'Print map preview'});
  await expect(preview).toBeVisible({timeout:45000});
  await expect(preview).toContainText('My topographic vicinity map');
  await expect(preview).toContainText('places.csv');
  await expect(preview).toContainText('Warm atlas');
  const image=preview.getByRole('img');
  await expect(image).toHaveAttribute('src',/^data:image\/png;base64,/);
  expect((await image.getAttribute('src'))!.length).toBeGreaterThan(50000);
  await page.screenshot({path:'test-results/map-maker-preview.png',fullPage:true});
  await page.emulateMedia({media:'print'});
  await expect(page.locator('#root')).toBeHidden();
  await expect(image).toBeVisible();
  const pdf=await page.pdf({path:'test-results/topographic-map.pdf',printBackground:true,preferCSSPageSize:true});
  expect(pdf.toString('latin1').match(/\/Type\s*\/Page\b/g)).toHaveLength(1);
  await page.emulateMedia({media:'screen'});
  await preview.getByRole('button',{name:'Close preview'}).click();
  await page.getByRole('button',{name:'Draw a boundary',exact:true}).click();
  await expect(page.locator('.map')).toHaveAttribute('data-tool','boundary');
  const map=page.locator('.map');
  await map.click({position:{x:150,y:250}});
  await map.click({position:{x:300,y:250}});
  await map.dblclick({position:{x:300,y:400}});
  await expect(page.getByText('Boundary drawn.',{exact:false})).toBeVisible();
  await expect(map).toHaveAttribute('data-tool','explore');
  await page.getByRole('button',{name:'Load / update Landsat'}).click();
  await expect(page.getByText('Landsat service could not load.',{exact:false})).toBeVisible({timeout:30000});
});
